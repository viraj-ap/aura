// Embeds pdf.js (library + worker) into a TS module as strings, so PDFs are parsed fully offline
// inside the hidden WebView. Runs on postinstall; output is generated, don't edit it.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve('pdfjs-dist/package.json')), 'legacy/build');
const lib = readFileSync(join(dir, 'pdf.min.mjs'), 'utf8');
const worker = readFileSync(join(dir, 'pdf.worker.min.mjs'), 'utf8');
const version = JSON.parse(readFileSync(join(dir, '../../package.json'), 'utf8')).version;
const out = new URL('../src/attachments/pdfjs.generated.ts', import.meta.url);
writeFileSync(out, `// Generated by scripts/bundle-pdfjs.mjs from pdfjs-dist ${version}. Do not edit.\n` +
  `export const PDFJS_LIB = ${JSON.stringify(lib)};\nexport const PDFJS_WORKER = ${JSON.stringify(worker)};\n`);
console.log(`pdf.js ${version} bundled (${((lib.length + worker.length) / 1e6).toFixed(1)} MB)`);
